const LOCALE_KEY = 'mebel.locale';

interface I18n {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: Key, params?: Record<string, string | number>) => string;
  status: (s: OrderStatus) => string;
  unit: (u: Unit) => string;
  terms: (t: PaymentTerms) => string;
  method: (m: PaymentMethod) => string;
  level: (l: StockLevel) => string;
  errorText: (code: string, fallback: string) => string;
  /** Mahsulot nomi tilga qarab */
  name: (x: { nameUz: string; nameRu: string }) => string;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const device = getLocales()[0]?.languageCode === 'ru' ? 'ru' : 'uz';
  const [locale, setLocaleState] = useState<Locale>(device);

  useEffect(() => {
    void secureStorage.get(LOCALE_KEY).then((v) => {
      if (v === 'uz' || v === 'ru') setLocaleState(v);
    });
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    void secureStorage.set(LOCALE_KEY, l);
  }, []);

  const value = useMemo<I18n>(() => {
    const dict = locale === 'ru' ? ru : uz;
    return {
      locale,
      setLocale,
      t: (key, params) => (dict[key] ?? key).replace(/\{(\w+)\}/g, (_, k: string) => String(params?.[k] ?? '')),
      status: (s) => STATUS[locale][s],
      unit: (u) => UNIT[locale][u],
      terms: (x) => TERMS[locale][x],
      method: (m) => METHOD[locale][m],
      level: (l) => LEVEL[locale][l],
      errorText: (code, fallback) => ERRORS[locale][code] ?? fallback,
      name: (x) => (locale === 'ru' ? x.nameRu : x.nameUz),
    };
  }, [locale, setLocale]);

  return <Ctx value={value}>{children}</Ctx>;
}

export function useI18n() {
  const c = use(Ctx);
  if (!c) throw new Error('I18nProvider kerak');
  return c;
}
